"""Build src/route-data.js from the converted OpenStreetMap / GSI alignment (utsunomiya.json).

usage: python3 -I tools/make_route_data.py <utsunomiya.json> src/route-data.js

The input is produced from OSM relation 12210362 (JR宇都宮線, down main track) and the GSI
elevation tiles: points every 10 m with x (east), z (south), heading th (0 = north, + = west),
curvature k and an estimated formation height. Data © OpenStreetMap contributors (ODbL 1.0);
elevation 出典: 国土地理院 標高タイル（加工して作成）.
"""
import json, sys

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src, encoding='utf-8'))
P = d['points']
ds = round(P[1]['s'] - P[0]['s'], 3)
assert all(abs(P[i + 1]['s'] - P[i]['s'] - ds) < 1e-6 for i in range(len(P) - 1))

def arr(vals, fmt):
    return '[' + ','.join(fmt % v for v in vals) + ']'

def num(v, nd):
    s = f'{v:.{nd}f}'
    if '.' in s: s = s.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '', '-') else s

stations = []
for s in d['stations']:
    stations.append({k: s[k] for k in ('name', 's', 'pf_s0', 'pf_s1') if k in s})

out = []
out.append('// Real alignment of the 宇都宮線 down main track, 上野 → 宇都宮 (generated by tools/make_route_data.py).')
out.append('// Track geometry © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright),')
out.append('// relation 12210362. Elevation 出典: 国土地理院 標高タイル（加工して作成）.')
out.append('// Frame: x = east, z = south (m), origin = 上野; th = heading (0 = north, + = left / west);')
out.append('// k = curvature 1/m (+ = left); e = estimated track height above sea level (m).')
out.append('export const ALIGN = {')
out.append(f'  s0: {num(P[0]["s"], 1)}, ds: {num(ds, 3)}, n: {len(P)},')
out.append('  x: [' + ','.join(num(p['x'], 2) for p in P) + '],')
out.append('  z: [' + ','.join(num(p['z'], 2) for p in P) + '],')
out.append('  th: [' + ','.join(num(p['th'], 5) for p in P) + '],')
out.append('  k: [' + ','.join(num(p['k'] * 1e6, 0) for p in P) + '],   // ×1e-6')
out.append('  e: [' + ','.join(num(p['elev'], 1) for p in P) + '],')
out.append('};')
out.append('/** OSM stop positions (s, roughly mid-platform) and platform extents where mapped */')
out.append('export const OSM_STATIONS = ' + json.dumps(stations, ensure_ascii=False) + ';')
out.append('/** curves from the smoothed curvature: s0, s1, R (m), dir (+1 left) */')
out.append('export const OSM_CURVES = ' + json.dumps([{k: c[k] for k in ('s0', 's1', 'R', 'dir')} for c in d['curves']]) + ';')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('points', len(P), 'bytes', sum(len(l) + 1 for l in out))
